import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
const html=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const code=html.slice(html.indexOf('function createMusicPlayer('),html.indexOf('const musicPlayer='));
const create=vm.runInNewContext(code+';createMusicPlayer');
let settings={bgm:true,bgmVol:.7},hidden=false,calls=0,resolvePlay;
const audio={paused:true,volume:0,play(){calls++;this.paused=false;return Promise.resolve();},pause(){this.paused=true;}};
const player=create(audio,()=>settings,()=>hidden);
assert.equal(calls,0,'title has no playback');
player.resume();assert.equal(calls,0,'other interactions before entry stay silent');
player.setMusic(true);assert.equal(calls,1,'entry starts BGM');assert.equal(audio.loop,true);
player.resume();assert.equal(calls,1,'no duplicate playback');
settings.bgm=false;player.setMusic(false);assert.equal(audio.paused,true);
player.resume();assert.equal(calls,1,'muted remains silent');
settings.bgm=true;player.setMusic(true);hidden=true;player.pause();player.resume();assert.equal(audio.paused,true);
hidden=false;player.resume();assert.equal(audio.paused,false);
settings.bgmVol=0;player.applyVolumes();assert.equal(audio.volume,0);
settings.bgmVol=9;player.applyVolumes();assert.equal(audio.volume,.55);
audio.pause();audio.play=()=>{calls++;return Promise.reject(new Error('blocked'));};player.resume();await new Promise(r=>setImmediate(r));
audio.play=()=>new Promise(r=>{resolvePlay=()=>{audio.paused=false;r();};});player.resume();settings.bgm=false;player.setMusic(false);resolvePlay();await Promise.resolve();assert.equal(audio.paused,true,'late playback cannot override mute');
const savedOff={...settings,bgm:false};const off=create(audio,()=>savedOff,()=>false);const before=calls;off.setMusic(false);assert.equal(calls,before);
const embedded=html.match(/id="gardenMusic"[^>]*src="data:audio\/mpeg;base64,([^"]+)"/)[1];
assert.equal(crypto.createHash('sha256').update(Buffer.from(embedded,'base64')).digest('hex'),'e574ca6759477190071a16176d6e3eb4011e5551b738a9b0c014c344fedd7c12');
assert.ok(html.includes('制作・提供：'));assert.ok(html.includes('rVoYCM6Gw3E'));
assert.ok(!html.includes('bgm=makeBgm(ctx,music)'),'synthesized track is disconnected');
assert.ok(html.includes('sfx.setMusic(state.settings.bgm); sfx.init(); sfx.resume(); sfx.soft();'));
console.log('PASS music: entry playback, mute, volume, loop, visibility, rejection, stale play, official MP3 and credit');
